         * Этот метод — «команда на уничтожение». Он окончательно удаляет запись из системы.
            На пальцах это работает так:
            1. Подготовка и маскировка
            [HttpPost, ActionName("Delete")]: Это интересная деталь. В браузере кнопка может вести на адрес /Delete, 
        но в коде функция называется DeleteConfirmed. Это сделано для того, чтобы случайно не удалить данные простым переходом по ссылке — удаление сработает только при нажатии кнопки.
            ValidateAntiForgeryToken: Опять же, «печать подлинности», чтобы никто извне не прислал команду на удаление от вашего имени.
            2. Проверка архива
            if (_context.DrAccounts == null)
            Программа проверяет: «А вообще шкаф с документами на месте?». Если доступа к таблице нет, она выдает сообщение о критической ошибке.
            3. Поиск «с поличным»
            Программа ищет в базе сразу две записи по номеру (id):
            draccounts — дебетовую часть.
            craccounts — кредитовую часть.
            Это как если бы вы искали две половинки одной разорванной купюры.
            4. Удаление (Синхронность)
            if (draccounts != null && craccounts != null)
            Если обе половинки найдены, программа дает команду: «Убрать обе!».
            Remove — это еще не физическое удаление. Это просто пометка «в корзину».
            SaveChangesAsync() — а вот здесь сервер реально берет ластик и стирает эти записи из файла базы данных навсегда.
            5. Возврат
            После того как всё стерто, сервер возвращает вас на главную страницу (Index), где удаленной строки уже нет.
            Итог «на пальцах»:
            Представьте, что вы — архивариус. К вам приходят и говорят: «Уничтожьте запись №5».
            Вы проверяете, что приказ настоящий (Токен).
            Вы идете к стеллажу.
            Достаете папку из Дебетового отдела и папку из Кредитового отдела под номером 5.
            Кладете их в шредер.
            Нажимаете кнопку «Пуск» (SaveChangesAsync).
            Возвращаетесь на рабочее место и показываете обновленный список документов.
        */
		// POST: DrAccount/Delete/5
		[HttpPost, ActionName("Delete")]
        [ValidateAntiForgeryToken]
        public async Task<IActionResult> DeleteConfirmed(int id)
        {
            if (_context.DrAccounts == null)
            {
                return Problem("Entity set 'ApplicationDbContext.DrAccounts'  is null.");
            }
            var draccounts = await _context.DrAccounts.FindAsync(id);
            var craccounts = await _context.CrAccounts.FindAsync(id);
            if (draccounts != null && craccounts != null)
            {
                _context.DrAccounts.Remove(draccounts);
                _context.CrAccounts.Remove(craccounts);
            }

            await _context.SaveChangesAsync();
            return RedirectToAction(nameof(Index));
        }

