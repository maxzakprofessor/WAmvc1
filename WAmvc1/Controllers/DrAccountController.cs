		/*
         Есть один нюанс: В этом коде дважды вызывается SaveChangesAsync. Хотите объясню, почему в программировании обычно стараются вызывать его один раз в самом конце?
        Да
        Вызов SaveChangesAsync() — это самая «тяжелая» и ответственная задача для сервера. Это физическая запись данных на жесткий диск.
        Представьте ситуацию «на пальцах»:
        Вы — бухгалтер, и вам нужно записать данные в две разные книги (Дебет и Кредит), которые лежат в сейфе в другом конце здания.
        Как делает ваш текущий код:
        Вы берете данные для Дебета.
        Идете через всё здание к сейфу.
        Открываете его, записываете, закрываете.
        Возвращаетесь к столу.
        Берете данные для Кредита.
        Снова идете через всё здание к сейфу.
        Открываете, записываете, закрываете.
        Проблема: Вы сходили два раза там, где можно было сходить один. Это медленнее.
        Главная опасность (Транзакции):
        А теперь представьте: вы сходили первый раз и успешно записали Дебет. Но когда вы пошли второй раз (с Кредитом), в здании выключили свет, или сейф заклинило.
        Результат: В базе данных появился Дебет, но нет Кредита. Данные «развалились», баланс не сошелся.
        Как сделать правильно (Один вызов):
        В Entity Framework можно сделать так:
        csharp
        _context.DrAccounts.Add(drAccount); // Просто пометили: "надо добавить"
        _context.CrAccounts.Add(crAccount); // Тоже просто пометили

        await _context.SaveChangesAsync(); // ОДИН раз сходили к сейфу и записали ВСЁ сразу
        Используйте код с осторожностью.

        Почему это круто:
        Скорость: Один поход к базе данных вместо двух.
        Принцип «Всё или ничего»: Если при записи произойдет сбой, база не запишет ни одну из частей. У вас не будет «половинчатых» данных. Либо оба счета создадутся, либо ни одного.
        Итог:
        Когда вы вызываете SaveChangesAsync() один раз в конце метода, вы страхуете себя от ошибок синхронизации.
         */

		/*
		 * Этот метод — «приемщик анкет и синхронный дубликатор». Он срабатывает, когда вы заполнили форму на сайте и нажали кнопку «Сохранить».
	   На пальцах это работает так:
	   1. Защита и фильтры
	   [HttpPost]: Это значит, что метод работает только на отправку данных (когда нажата кнопка в форме).
	   [ValidateAntiForgeryToken]: Защита от «поддельных» запросов. Это как печать на документе, подтверждающая, что форму заполнили именно на вашем сайте, а не прислали подделку со стороны.
	   [Bind(...)]: Безопасность. Мы разрешаем пользователю менять только Title и RevExpAccount. Даже если хакер подкинет в запрос другие данные, сервер их проигнорирует.
	   2. Создание «Зеркала» (CrAccount)
	   В самом начале метода происходит магия:
	   CrAccount crAccount = new CrAccount() { ... }
	   Программа берет данные, которые вы ввели для дебетового счета (Dr), и копирует их один-в-один для кредитового счета (Cr). Это автоматизация: пользователь заполняет одну форму, а сервер готовит данные сразу для двух таблиц.
	   3. Проверка и сохранение
	   if (ModelState.IsValid) — Проверка: «Все ли поля заполнены правильно? Нет ли ошибок в тексте?». Если всё ок, идем дальше:
	   Логика «Новый или Старый»:
	   Если DrAccountId == 0: Сервер понимает, что это новичок, и говорит: «Добавить в список!» (Add).
	   Если ID есть: Сервер понимает, что это редактирование, и говорит: «Обновить данные!» (Update).
	   Двойная запись:
	   Сначала сохраняем дебетовый счет (DrAccounts).
	   Потом точно так же сохраняем кредитовый (CrAccounts).
	   SaveChangesAsync(): Это финальный щелчок замка. Только после этой команды данные физически записываются на диск в файл базы данных.
	   4. Финал
	   Если всё прошло успешно: Вас перекидывает на главную страницу (RedirectToIndex).
	   Если были ошибки (например, пустое поле): Вас оставляют на той же странице (return View(drAccount)), чтобы вы могли исправить ошибки.
	   Итог «на пальцах»:
	   Вы приносите заполненный бланк. Сервер:
	   Проверяет «печать» безопасности.
	   Делает ксерокопию этого бланка для другого отдела (Кредитового).
	   Смотрит: «Так, это новая запись или замена старой?».
	   Записывает оба варианта в архив.

		*/
