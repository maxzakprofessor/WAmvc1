            Выдача результата:
            return View(список): Если вы — тот самый «учитель», сервер берет данные из базы, «наклеивает» их на HTML-шаблон и показывает вам таблицу со счетами.
            return View(): Если вы — кто-то другой (или аноним), сервер просто покажет пустую страницу без данных из базы. 
            Почему это написано именно так:
            async и await: Это как работа по предзаказу. Сервер не «зависает», пока база данных ищет записи, а может в 
