            Вы говорите: «Я хочу исправить ошибки в карточке №5». Сотрудник достает карточку №5 из архива и кладет перед вами.
            Почему это удобно?
            Разработчик не создавал две разные страницы для «Создать» и «Изменить». Он использовал одну и ту же страницу, просто научил её подставлять либо пустоту, либо данные из базы.

