/*Этот блок кода — «выбор режима работы». Он определяет, как сервер будет вести себя в зависимости от того, где он запущен: 
 * на компьютере разработчика или на реальном сервере в интернете.
На пальцах:
1. Режим разработки (IsDevelopment)
Когда вы пишете код у себя на компьютере, вам нужно максимум информации об ошибках.
app.UseMigrationsEndPoint(): Если вы забыли обновить базу данных (не применили миграции), 
сервер не просто выдаст ошибку, а покажет удобную страницу с кнопкой «Применить миграции». Это экономит время разработчику.
2. Режим «В продакшене» (else)
Когда сайт запущен для реальных пользователей, показывать им технические ошибки или детали базы данных опасно и некрасиво.
app.UseExceptionHandler("/Home/Error"): Если на сайте что-то сломается (произойдет программный сбой), пользователь не увидит 
«страшный» технический текст с кодом. Его вежливо перенаправят на красивую страницу ошибки: «Извините, что-то пошло не так».
app.UseHsts(): Это команда для браузеров. Она говорит: «Запоминай, что на этот сайт можно заходить только по безопасному 
соединению HTTPS». Даже если пользователь через месяц попробует зайти по обычному HTTP, браузер сам переключит его на защищенный протокол ради безопасности.
 */
if (app.Environment.IsDevelopment())
{
    app.UseMigrationsEndPoint();
}
else
{
    app.UseExceptionHandler("/Home/Error");
    // The default HSTS value is 30 days. You may want to change this for production scenarios, see https://aka.ms/aspnetcore-hsts.
    app.UseHsts();
}
/*Безопасность и правила: Устанавливается защита (HTTPS).
 Эта строчка работает как строгий швейцар, который перенаправляет всех посетителей с опасного входа на безопасный. [1, 2]
На пальцах:
Есть протокол HTTP (незащищенный) и HTTPS (защищенный, с шифрованием). [2]
Если пользователь случайно введет адрес вашего сайта через http://, команда app.UseHttpsRedirection() автоматически 
«схватит» его и перекинет на тот же адрес, но уже через безопасный https://. [2, 3]
Зачем это нужно:
Чтобы данные между браузером и вашим сервером (например, пароли или данные из базы SQLite) передавались в зашифрованном 
виде и их нельзя было перехватить по пути. [2]
В вашем коде эта команда стоит перед обработкой запросов, чтобы безопасность обеспечивалась с самого начала сессии. [2, 3]*/
app.UseHttpsRedirection();
/*
 Эта строчка — «разрешение на выдачу посылок».
На пальцах:
Представьте, что ваш сервер — это очень умный библиотекарь. Он умеет выполнять сложные расчеты и искать данные в базе. 
Но если вы попросите его просто дать вам фотографию или листок с правилами оформления (CSS), он ответит: «Я этим не занимаюсь, я тут логику считаю».
Команда app.UseStaticFiles() говорит серверу:
«Если кто-то просит просто файл (картинку, иконку, стиль или готовый скрипт), не мучайся с логикой, 
а просто загляни в специальную папку (обычно это wwwroot) и отдай этот файл как есть».
Зачем это нужно:
Дизайн: Чтобы ваш сайт был красивым (загружались файлы .css).
Картинки: Чтобы пользователи видели логотипы и фото.
Интерактив: Чтобы работали простые скрипты на стороне браузера (файлы .js).
Без этой строки:
Ваш сайт будет выглядеть как черно-белый текст на белом фоне, потому что браузер не сможет загрузить 
ни одного файла оформления, даже если они лежат у вас в проекте.

 */
app.UseStaticFiles();
/*
 * Эта строчка — «навигатор» или «сортировочный центр» вашего приложения.
На пальцах:
Когда запрос от пользователя прилетает на сервер, сервер сначала должен понять: «А куда вообще хочет попасть этот человек?».
app.UseRouting() делает следующее:
Смотрит на адрес (URL), который ввел пользователь (например, /Home/Index).
Сверяет его со списком всех возможных путей в программе.
Принимает решение: «Так, этот запрос мы отправим в Домашний контроллер».
Важный момент:
Сама по себе эта команда еще никого никуда не отправляет. Она только выбирает маршрут и прикрепляет эту информацию к запросу. 
Это как если бы на посылку наклеили ярлык: «Отправить в отдел электроники», но саму коробку еще не переместили.
Почему она стоит именно здесь?
В вашем коде она стоит перед app.UseAuthorization(). Это логично: сервер сначала должен понять, куда вы идете (Routing), 
чтобы потом проверить, есть ли у вас право туда заходить (Authorization).
 */
app.UseRouting();
/*
 * Эта строчка — «проверка паспорта» на входе.
На пальцах:
Если UseAuthorization (о которой мы говорили раньше) проверяет ваши права (что вам можно делать), то UseAuthentication проверяет, кто вы вообще такой.
Представьте ситуацию в клубе:
Authentication (UseAuthentication): Вы подходите к охраннику и показываете паспорт. Охранник смотрит: «Да, 
это Иван Иванович, личность подтверждена». Вы зашли в здание.
Authorization (UseAuthorization): Вы пытаетесь пройти в VIP-зону. Охранник смотрит в список: «Иван Иванович есть, но в VIP-списке его нет». И не пускает.
Почему это важно в коде:
Эта команда вытаскивает данные о пользователе из куки (cookies) или токена.
Она «узнаёт» пользователя и записывает его имя и ID в специальный объект User, чтобы программа знала, чьи это данные.
Она обязательно должна стоять перед UseAuthorization, потому что нельзя проверить права доступа, не зная, кто перед нами.
Итог: без этой строки сервер будет считать всех посетителей «анонимами», даже если они только что ввели логин и пароль.

 */
app.UseAuthentication();
/*Безопасность и правила: правила авторизации.
 Эта строчка — «проверка пропусков» у тех, кто уже вошел в здание.
Если UseHttpsRedirection — это безопасный вход, то UseAuthorization — это охранник внутри, который проверяет: 
«А есть ли у тебя права находиться именно в этой комнате?»
На пальцах:
Аутентификация (обычно идет перед этим) — это проверка паспорта: «Ты тот, за кого себя выдаешь?».
Авторизация (UseAuthorization) — это проверка уровня доступа: «Ты обычный гость или администратор? Тебе можно 
только смотреть на товары или ты можешь их удалять?».
Важный нюанс:
В вашем коде эта команда стоит стандартным «заборчиком». Она подготавливает сервер к тому, 
что если вы в будущем повесите на какой-то контроллер или метод ярлык [Authorize], 
программа автоматически проверит права пользователя перед тем, как пустить его внутрь.*/
app.UseAuthorization();
/*
 * Эта строчка — «адресная книга» или правила навигации для вашего сайта. Она объясняет серверу, как превращать скучный URL 
 * в строке браузера в запуск конкретного кода.
На пальцах:
Когда пользователь заходит на сайт, он вводит адрес. Эта команда берет этот адрес и «разрезает» его на три части по шаблону {контроллер}/{действие}/{айди}:
controller=Home: Первая часть пути — это имя «отдела» (класса). Если пользователь ничего не ввел (просто зашел на сайт), по умолчанию выбирается отдел Home.
action=Index: Вторая часть — это конкретная задача (функция) внутри этого отдела. По умолчанию запускается задача Index (главная страница).
id?: Третья часть — это номер конкретной записи (например, номер товара). Знак вопроса означает, что это необязательно.
Примеры, как это работает:
Вы ввели: ://mysite.com → Сервер понимает: Home / Index.
Вы ввели: ://mysite.com → Сервер идет в отдел Products, запускает задачу Details и передает ей номер 5.
Зачем это нужно:
Без этой настройки сервер не поймет, какую страницу показать первой, и будет выдавать ошибку при попытке перейти в любой 
раздел сайта. Это база для классических сайтов на MVC.
 */
app.MapControllerRoute(
    name: "default",
    pattern: "{controller=Home}/{action=Index}/{id?}");
/*
 * Эта строчка — «дополнительная карта» для поиска страниц.
На пальцах:
В ASP.NET есть два способа создавать страницы:
MVC (который мы разобрали выше) — где есть отдельный «мозг» (Контроллер) и отдельный «внешний вид» (Представление).
Razor Pages — где страница и её логика живут вместе в одном файле (как в старом добром вебе, только современно).
Зачем это в вашем коде:
Поскольку вы добавили систему Identity (вход, регистрация), она в ASP.NET Core по умолчанию сделана на Razor Pages.
Что делает MapRazorPages():
Она говорит серверу: «Если ты не нашел подходящего адреса среди Контроллеров (MVC), загляни в папку Pages. Возможно, 
нужная страница (например, /Account/Login) находится там».
Итог:
Без этой команды ваша система логина и регистрации просто не откроется, так как сервер не будет знать, где искать эти файлы.

 */

app.MapRazorPages();
/*
 Это финальный рубильник. Она запускает всё то, что вы «настроили» строчками выше.
На пальцах:
До этой команды ваш код — это просто список инструкций на бумаге. Вы объяснили программе, 
где база данных, как проверять пропуска и куда направлять запросы, но сервер всё ещё «спит».
Когда выполняется app.Run():
Сервер «просыпается» и начинает слушать входящий интернет-трафик.
Приложение переходит в режим бесконечного цикла: оно не закрывается само по себе, а ждет запросов от пользователей.
Если вы закроете консоль с запущенным приложением, это фактически нажмет «стоп» для этой команды.
Итог: это точка невозврата. Весь код до неё — это настройка, а после вызова app.Run() начинается реальная работа сервера.

 */
app.Run();
