    options.UseSqlite(connectionString));
/*
Эта строчка — «диагностический сканер» для базы данных, который работает только во время разработки.
На пальцах:
Представьте, что вы строите дом и у вас возникли проблемы с фундаментом (базой данных). 
Вместо того чтобы просто сказать «что-то сломалось», этот инструмент выдает подробный отчет.
Что конкретно он делает:
Ловит ошибки базы: Если вы забыли создать таблицы или применили неправильное обновление (миграцию), этот фильтр перехватывает ошибку.
Предлагает решение: Вместо белого экрана с непонятным кодом он показывает красивую страницу, где прямо написано: «Похоже, вы забыли обновить базу данных».
Дает «волшебную кнопку»: Часто на этой странице появляется кнопка «Apply Migrations». Вы нажимаете её прямо в браузере, и программа сама чинит базу данных.
Зачем это нужно:
Это экономит кучу времени. Вам не нужно лезть в консоль и писать команды — сервис сам понимает, что база «отстала» от кода, и предлагает это исправить в один клик.
Важно:
Эта штука работает в паре с app.UseMigrationsEndPoint(), о которой мы говорили раньше. Один находит проблему, другой показывает кнопку для её решения.
 */

builder.Services.AddDatabaseDeveloperPageExceptionFilter();
/*
 * Этот блок кода — это «связка системы пользователей с базой данных».
На пальцах, это работает как установка электронного замка и подключение его к хранилищу данных:
1. AddDefaultIdentity(...)
Это установка самого замка.
Вы говорите: «Мне нужна стандартная система регистрации и входа».
IdentityUser — это стандартная «карточка пользователя», в которой уже есть поля: Логин, Пароль, Email и Номер телефона.
RequireConfirmedAccount = true — это строгая настройка: «Если человек зарегистрировался, он считается "заблокированным", 
пока не подтвердит свой email».
2. .AddEntityFrameworkStores<ApplicationDbContext>()
Это подключение замка к сейфу.
Сама по себе система Identity — это просто логика («как проверять», «как шифровать»). Ей нужно место, где физически лежат списки пользователей.
Этой строчкой вы говорите: «Всех пользователей и их зашифрованные пароли записывай в наш сейф — ApplicationDbContext (который ведет в вашу базу SQLite)».
Почему это важно именно в связке:
Если вы напишете первую часть, но забудете .AddEntityFrameworkStores, программа выдаст ошибку: «Я знаю, как проверять пользователей, но я не знаю, где их искать!».
 */
builder.Services.AddDefaultIdentity<IdentityUser>(options => options.SignIn.RequireConfirmedAccount = true)
    .AddEntityFrameworkStores<ApplicationDbContext>();
/*
 * Эта строчка — «закупка оборудования» для создания классического сайта.
На пальцах:
ASP.NET Core может быть просто «почтовым ящиком» для пересылки данных (API), а может быть полноценным заводом по производству веб-страниц.
Что конкретно делает эта команда:
Нанимает Контроллеры (Controllers): Это «мозги» вашего сайта. Они принимают запросы от пользователя, решают, что делать, и достают данные из базы.
Закупает Виды (Views): Это шаблоны страниц (HTML-файлы). В них написано, как сайт должен выглядеть: где будет меню, где картинки, а где текст.
Склеивает их вместе: Эта команда учит сервер брать данные из «мозга» и вставлять их в «шаблон», чтобы в итоге отправить пользователю готовую красивую страницу.
В чем разница:
Если бы вы написали AddControllers(), ваш сервер мог бы выдавать только сухие данные (цифры и текст в формате JSON).
С AddControllersWithViews() ваш сервер теперь умеет «рисовать» полноценный интерфейс с кнопками, формами и дизайном.
Итог:
Эта строка говорит серверу: «Готовься, мы будем делать полноценный сайт с визуальными страницами (MVC), а не просто передавать данные».
 */
builder.Services.AddControllersWithViews();

